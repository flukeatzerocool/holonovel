#!/usr/bin/env node
/**
 * check-context-audit.ts — the checked context audit table (REQ-661/T798). [gate]
 *
 * Parses every `requireNovel()` call site in the four tool-surface files,
 * attributes each to its enclosing tool registration and `case` label (or to
 * `guard` when the call sits at handler/helper scope), and compares the
 * observed multiset with `src/core/context-audit.ts`. Fails when a site has no
 * row, a row's `sites` count disagrees with the code, a row is stale, a key is
 * duplicated, or a row's class/disposition is outside the allowed set.
 *
 * Modes:
 *   --check      (default) compare the table and the committed page
 *   --observed   print observed keys and site counts, sorted
 *   --write      regenerate docs/authoring-surfaces/context-audit.md
 *   --stdout     print what --write would write, do not touch the file
 *
 * The generated page is byte-deterministic: rows are sorted by tool then
 * action, and no timestamp or version stamp appears in it.
 *
 * Usage: tsx scripts/check-context-audit.ts [--check|--observed|--write|--stdout]
 * Exit codes: 0 = pass, 1 = a finding, 2 = fatal.
 */
import { readFileSync, writeFileSync, existsSync, mkdirSync } from "node:fs";
import { join, dirname } from "node:path";
import { pathToFileURL } from "node:url";
import { CONTEXT_AUDIT } from "../src/core/context-audit.js";
import type { AuditRow } from "../src/core/context-audit.js";

const ROOT = join(import.meta.dirname, "..");
const FILES = [
  "src/index.ts",
  "src/tools/knowledge.ts",
  "src/tools/world-crud.ts",
  "src/tools/world-model.ts",
];
const PAGE = join(ROOT, "..", "docs", "authoring-surfaces", "context-audit.md");

const CLASSES = new Set(["novel-only", "context-agnostic", "wrongly-novel-bound"]);
const DISPOSITIONS = new Set(["keep", "A2-fix", "A3", "A4", "A5"]);

const REG_TOOL = /server\.registerTool\("([a-z_]+)"/;
const REG_LOCAL = /^\s*register\("([a-z_]+)"/;
const CASE_LABEL = /^\s*case "([a-z_0-9]+)":/;

export interface ObservedSite {
  key: string;
  count: number;
}

/** Attribute every `requireNovel()` call to (tool, action|guard). Pure: pass file text. */
export function observeSources(sources: Array<{ file: string; text: string }>): { sites: ObservedSite[]; total: number } {
  const tally = new Map<string, number>();
  let total = 0;
  for (const { text } of sources) {
    let tool: string | null = null;
    let action = "guard";
    for (const line of text.split("\n")) {
      const reg = REG_TOOL.exec(line) ?? REG_LOCAL.exec(line);
      if (reg) {
        tool = reg[1];
        action = "guard";
        continue;
      }
      const label = CASE_LABEL.exec(line);
      if (label) {
        action = label[1];
        continue;
      }
      if (line.includes("requireNovel()") && tool) {
        const key = `${tool}.${action}`;
        tally.set(key, (tally.get(key) ?? 0) + 1);
        total += 1;
      }
    }
  }
  const sites = [...tally.entries()]
    .map(([key, count]) => ({ key, count }))
    .sort((a, b) => a.key.localeCompare(b.key));
  return { sites, total };
}

export function auditFindings(observed: ObservedSite[], rows: AuditRow[]): string[] {
  const findings: string[] = [];
  const seen = new Set<string>();
  const byKey = new Map<string, AuditRow>();

  for (const row of rows) {
    const key = `${row.tool}.${row.action}`;
    if (seen.has(key)) findings.push(`duplicate row: ${key}`);
    seen.add(key);
    byKey.set(key, row);
    if (!CLASSES.has(row.class)) findings.push(`${key}: unknown class '${row.class}'`);
    if (!DISPOSITIONS.has(row.disposition)) findings.push(`${key}: unknown disposition '${row.disposition}'`);
    if (!Number.isInteger(row.sites) || row.sites < 0) findings.push(`${key}: sites must be a non-negative integer`);
  }

  for (const site of observed) {
    const row = byKey.get(site.key);
    if (!row) {
      findings.push(`unclassified call site: ${site.key} (${site.count})`);
      continue;
    }
    if (row.sites !== site.count) {
      findings.push(`${site.key}: row says ${row.sites} site(s), code has ${site.count}`);
    }
  }

  for (const row of rows) {
    if (row.sites === 0) continue;
    const key = `${row.tool}.${row.action}`;
    if (!observed.some((s) => s.key === key)) findings.push(`stale row: ${key} says ${row.sites} site(s), code has none`);
  }

  return findings;
}

export function renderPage(rows: AuditRow[]): string {
  const sorted = [...rows].sort((a, b) => `${a.tool}.${a.action}`.localeCompare(`${b.tool}.${b.action}`));
  const total = sorted.reduce((sum, r) => sum + r.sites, 0);
  const header = [
    "# Context audit — every `requireNovel()` call site",
    "",
    `Generated by \`npm run check-context-audit -- --write\`. ${sorted.length} rows, ${total} call sites.`,
    "",
    "Classes: `novel-only` (play state needs a Novel), `context-agnostic` (valid on another store),",
    "`wrongly-novel-bound` (requires a Novel today but should not). Dispositions name the increment that",
    "resolves a wrongly-bound row, or `keep`.",
    "",
    "| Tool | Action | Class | Scope | Novel-capable | Wrapped | Sites | Disposition |",
    "|---|---|---|---|---|---|---|---|",
  ];
  const body = sorted.map(
    (r) =>
      `| \`${r.tool}\` | \`${r.action}\` | ${r.class} | ${r.scope} | ${r.novelCapable ? "yes" : "no"} | ${
        r.wrapped ? "yes" : "no"
      } | ${r.sites} | ${r.disposition} |`,
  );
  return [...header, ...body, ""].join("\n");
}

function usage(): void {
  console.log("Usage: tsx scripts/check-context-audit.ts [--check|--observed|--write|--stdout]");
  console.log("  --check     compare the table and the committed page (default)");
  console.log("  --observed  print observed keys and site counts");
  console.log("  --write     regenerate docs/authoring-surfaces/context-audit.md");
  console.log("  --stdout    print the page instead of writing it");
}

function main(): void {
  const argv = process.argv.slice(2);
  if (argv.includes("--help") || argv.includes("-h")) {
    usage();
    process.exit(0);
  }
  const known = ["--check", "--observed", "--write", "--stdout"];
  const unknown = argv.filter((a) => !known.includes(a));
  if (unknown.length > 0) {
    console.error(`check-context-audit: unknown flag(s): ${unknown.join(", ")}`);
    usage();
    process.exit(1);
  }

  const sources = FILES.map((file) => ({ file, text: readFileSync(join(ROOT, file), "utf-8") }));
  const { sites, total } = observeSources(sources);

  if (argv.includes("--observed")) {
    for (const s of sites) console.log(`${s.key}\t${s.count}`);
    console.error(`\n${sites.length} keys, ${total} call sites`);
    process.exit(0);
  }

  if (argv.includes("--write") || argv.includes("--stdout")) {
    const page = renderPage(CONTEXT_AUDIT);
    if (argv.includes("--stdout")) {
      process.stdout.write(page);
      process.exit(0);
    }
    mkdirSync(dirname(PAGE), { recursive: true });
    writeFileSync(PAGE, page);
    console.log(`wrote ${PAGE}`);
    process.exit(0);
  }

  const findings = auditFindings(sites, CONTEXT_AUDIT);

  // Page freshness: the committed page must match what --write would emit.
  if (existsSync(PAGE)) {
    const expected = renderPage(CONTEXT_AUDIT);
    const actual = readFileSync(PAGE, "utf-8");
    if (actual !== expected) findings.push("docs/authoring-surfaces/context-audit.md is stale: run --write");
  } else if (CONTEXT_AUDIT.length > 0) {
    findings.push("docs/authoring-surfaces/context-audit.md is missing: run --write");
  }

  console.log(`context audit: ${sites.length} observed keys, ${total} call sites, ${CONTEXT_AUDIT.length} rows`);
  if (findings.length === 0) {
    console.log("context audit: PASS");
    process.exit(0);
  }
  for (const f of findings) console.error(`  ${f}`);
  console.error(`context audit: FAIL (${findings.length} finding(s))`);
  process.exit(1);
}

// Import-safe: the pure helpers are exercised by test-context.ts (T798).
const invokedDirectly = process.argv[1] ? import.meta.url === pathToFileURL(process.argv[1]).href : false;
if (invokedDirectly) main();
