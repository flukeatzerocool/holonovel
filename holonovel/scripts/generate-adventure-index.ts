#!/usr/bin/env npx tsx
/**
 * generate-adventure-index.ts — emit the build-time adventure index. [build tool; gate with --check]
 *
 * Purpose: scan the adventure module directory (REQ-247), validate Appendix K
 * conventions (REQ-171a), extract each module's structure, and write the
 * discovery record the server reads for `spec_health.indexed_adventures`
 * (REQ-170), `[malformed-adventure]` (REQ-171b), and `[adventure-drift]`
 * (REQ-172): `adventures/index.json` plus the `adventure-index` table in
 * `holonovel/DECISIONS.md` (REQ-247c). Emission is byte-deterministic; the
 * `--check` mode gates freshness.
 *
 * Exit codes: 0 = written / in sync / report, 1 = stale or invalid input,
 * 2 = fatal (unreadable, unparsable).
 *
 * Usage: npx tsx scripts/generate-adventure-index.ts
 *          [--input <dir>] [--out <file>] [--decisions <file>]
 *          [--check] [--json] [--help]
 */

import { existsSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import { createHash } from "node:crypto";
import { join, resolve } from "node:path";
import { extractAdventureStructure } from "../src/core/adventure.js";

const SERVER_DIR = join(import.meta.dirname, "..");
const DEFAULT_INPUT = join(SERVER_DIR, "adventures");
const DEFAULT_OUT = join(DEFAULT_INPUT, "index.json");
const DEFAULT_DECISIONS = join(SERVER_DIR, "DECISIONS.md");
const START = "<!-- adventure-index:start — generated by `npm run build:adventure-index`; do not edit by hand -->";
const END = "<!-- adventure-index:end -->";

interface ModuleEntry {
  title: string;
  content_hash: string;
  player_visible: boolean;
  source: "build";
  scenes: string[];
  npcs: string[];
  locations: number;
  factions: number;
  malformed: Array<{ flag: string; convention: string; disposition: "skipped" | "partial" }>;
}

const USAGE = `Usage: npx tsx scripts/generate-adventure-index.ts [flags]

  --input <dir>       Adventure module directory (default holonovel/adventures)
  --out <file>        Index output (default <input>/index.json)
  --decisions <file>  DECISIONS.md to update (default holonovel/DECISIONS.md)
  --check             Regenerate in memory and fail when an output is stale
  --json              Print the index JSON instead of writing
  --help, -h          Show this help

Exit codes: 0 = in sync / written / report, 1 = stale or invalid input, 2 = fatal.`;

function fail(message: string): never {
  console.error(`[adventure-index] ${message}`);
  process.exit(1);
}

function parseArgs(argv: string[]): { input: string; out: string; decisions: string | null; check: boolean; json: boolean } {
  let input = DEFAULT_INPUT;
  let out: string | null = null;
  let decisions: string | null = DEFAULT_DECISIONS;
  let check = false;
  let json = false;
  for (let i = 0; i < argv.length; i++) {
    const arg = argv[i];
    if (arg === "--help" || arg === "-h") {
      console.log(USAGE);
      process.exit(0);
    } else if (arg === "--check") check = true;
    else if (arg === "--json") json = true;
    else if (arg === "--input" || arg === "--out" || arg === "--decisions") {
      const value = argv[++i];
      if (!value || value.startsWith("--")) fail(`${arg} requires a path`);
      if (arg === "--input") input = resolve(value);
      else if (arg === "--out") out = resolve(value);
      else decisions = value === "none" ? null : resolve(value);
    } else fail(`unknown flag: ${arg}`);
  }
  // A temp input directory must not rewrite the committed DECISIONS table
  // unless the caller asks for it explicitly.
  if (input !== DEFAULT_INPUT && decisions === DEFAULT_DECISIONS) decisions = null;
  return { input, out: out ?? join(input, "index.json"), decisions, check, json };
}

function build(): { json: string; decisionsBlock: string; modules: Record<string, ModuleEntry> } {
  const { input } = ARGS;
  if (!existsSync(input)) return { json: JSON.stringify({ modules: {} }, null, 2) + "\n", decisionsBlock: emptyBlock(), modules: {} };
  const files = readdirSync(input).filter((f) => f.endsWith(".md")).sort();
  const modules: Record<string, ModuleEntry> = {};
  for (const file of files) {
    const slug = file.replace(/\.md$/, "");
    const content = readFileSync(join(input, file), "utf-8");
    const structure = extractAdventureStructure(content, slug);
    const malformed = structure.malformed.map((m) => ({ flag: "[malformed-adventure]", ...m }));
    const skipped = structure.malformed.some((m) => m.disposition === "skipped");
    modules[slug] = {
      title: structure.title,
      content_hash: createHash("sha256").update(content).digest("hex"),
      player_visible: skipped ? false : structure.player_visible,
      source: "build",
      scenes: structure.locations.map((l) => l.name),
      npcs: structure.npcs.map((n) => n.name),
      locations: structure.locations.length,
      factions: structure.factions.length,
      malformed,
    };
  }
  const sorted = Object.fromEntries(Object.keys(modules).sort().map((k) => [k, modules[k]]));
  return { json: JSON.stringify({ modules: sorted }, null, 2) + "\n", decisionsBlock: renderBlock(sorted), modules: sorted };
}

function emptyBlock(): string {
  return [
    START,
    "### Adventure index (REQ-247c)",
    "",
    "No adventure modules are indexed — the discovery step is skipped when no",
    "adventure files are present (REQ-247c).",
    "",
    END,
  ].join("\n");
}

function renderBlock(modules: Record<string, ModuleEntry>): string {
  if (Object.keys(modules).length === 0) return emptyBlock();
  const rows = Object.entries(modules).map(([slug, m]) => {
    const flags = m.malformed.length
      ? m.malformed.map((x) => `${x.flag} ${x.convention} (${x.disposition})`).join("; ")
      : "conforming";
    return `| \`${slug}\` | ${m.title.replace(/\|/g, "\\|")} | ${m.scenes.join("; ") || "—"} | ${m.npcs.join("; ") || "—"} | ${m.locations} | ${m.factions} | ${m.content_hash.slice(0, 12)} | ${flags} |`;
  });
  return [
    START,
    "### Adventure index (REQ-247c)",
    "",
    "Validation: Appendix K conventions — an H1 title, `## Overview`,",
    "`## Adventure Hook`, and well-formed role-scoping markers — enforced by",
    "`npm run build:adventure-index`. The table is generated; edit the modules,",
    "not the rows.",
    "",
    "| Slug | Title | Scenes | NPC references | Locations | Factions | Content hash | Structural extraction |",
    "|---|---|---|---|---|---|---|---|",
    ...rows,
    "",
    END,
  ].join("\n");
}

function spliceDecisions(text: string, block: string): string {
  const start = text.indexOf("<!-- adventure-index:start");
  const end = text.indexOf(END);
  if (start >= 0 && end > start) {
    return text.slice(0, start) + block + text.slice(end + END.length);
  }
  return `${text.replace(/\s*$/, "")}\n\n${block}\n`;
}

function main(): void {
  const { input, out, decisions, check, json } = ARGS;
  if (!existsSync(input)) {
    if (check) fail(`input directory is missing: ${input}`);
    console.log(`[adventure-index] no adventure directory at ${input}; nothing to index`);
  }
  const built = build();
  if (json) {
    process.stdout.write(built.json);
    return;
  }
  if (check) {
    const problems: string[] = [];
    if (!existsSync(out)) problems.push(`index is missing — run npm run build:adventure-index (${out})`);
    else if (readFileSync(out, "utf-8") !== built.json) problems.push(`index is stale (${out})`);
    if (decisions) {
      const text = existsSync(decisions) ? readFileSync(decisions, "utf-8") : "";
      if (!text.includes(START)) problems.push(`DECISIONS.md is missing the adventure-index markers (${decisions})`);
      else if (spliceDecisions(text, built.decisionsBlock) !== text) problems.push(`DECISIONS.md adventure index is stale (${decisions})`);
    }
    if (problems.length > 0) fail(problems.join("; "));
    console.log("[adventure-index] PASS — index and DECISIONS table are fresh");
    return;
  }
  writeFileSync(out, built.json);
  if (decisions) {
    const text = existsSync(decisions) ? readFileSync(decisions, "utf-8") : "";
    writeFileSync(decisions, spliceDecisions(text, built.decisionsBlock));
  }
  console.log(`[adventure-index] wrote ${Object.keys(built.modules).length} module(s) to ${out}`);
}

const ARGS = parseArgs(process.argv.slice(2));

try {
  main();
} catch (error) {
  console.error("[adventure-index] fatal:", error instanceof Error ? error.message : error);
  process.exit(2);
}
