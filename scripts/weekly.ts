#!/usr/bin/env npx tsx
/**
 * weekly.ts — the weekly hygiene sweep. [entry point]
 *
 * Purpose: routine things done routinely. Runs the full gate, the hermetic
 * pipeline harness, the loop audit, the gate-cost report, and the register
 * freshness check, then writes a dated report. This is the single replenishment
 * point: findings become dated actions or an explicit record-and-close, so new
 * work cannot preempt in-flight work between slots.
 *
 * Usage: npx tsx scripts/weekly.ts [--date YYYY-MM-DD] [--dry-run]
 * Exit codes: 0 = every step passed, 1 = a step failed, 2 = fatal.
 */
import { spawnSync } from "node:child_process";
import { mkdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { handleHelp, parseFlag, parseValueFlag, rejectUnknown } from "./lib/args.js";

const ROOT = join(import.meta.dirname, "..");

const USAGE = `Usage: npx tsx scripts/weekly.ts [--date YYYY-MM-DD] [--dry-run]

  --date      Report date (default: local today).
  --dry-run   Run nothing; print the step list.
  --help      Show this message.
`;

interface Sweep {
  name: string;
  command: string[];
  /** Advisory steps report a failure without failing the sweep. */
  advisory?: boolean;
}

const SWEEPS: Sweep[] = [
  { name: "full gate", command: ["npm", "run", "check"] },
  { name: "pipeline harness", command: ["npm", "run", "test:pipeline"] },
  { name: "loop audit", command: ["npm", "run", "loop-audit", "--", "--write"] },
  { name: "gate cost", command: ["npm", "run", "gate-cost"] },
  { name: "registers", command: ["npm", "run", "check-registers:strict"] },
  { name: "markers", command: ["npm", "run", "check-markers"] },
];

function localToday(): string {
  const d = new Date();
  const pad = (n: number): string => String(n).padStart(2, "0");
  return `${d.getFullYear()}-${pad(d.getMonth() + 1)}-${pad(d.getDate())}`;
}

function main(): void {
  const argv = process.argv.slice(2);
  handleHelp(argv, USAGE);
  rejectUnknown(argv, new Set(["--date", "--dry-run", "--help", "-h"]), USAGE);
  const date = parseValueFlag(argv, "--date") ?? localToday();
  const dryRun = parseFlag(argv, "--dry-run");

  if (dryRun) {
    for (const sweep of SWEEPS) console.log(`would run: ${sweep.command.join(" ")}`);
    process.exit(0);
  }

  const rows: string[] = [];
  let failed = 0;
  for (const sweep of SWEEPS) {
    console.log(`\n=== ${sweep.name}: ${sweep.command.join(" ")} ===`);
    const started = Date.now();
    const result = spawnSync(sweep.command[0], sweep.command.slice(1), { cwd: ROOT, stdio: "inherit" });
    const seconds = ((Date.now() - started) / 1000).toFixed(1);
    const status = result.status ?? 1;
    if (status !== 0 && !sweep.advisory) failed++;
    rows.push(`| ${sweep.name} | \`${sweep.command.join(" ")}\` | ${status === 0 ? "pass" : sweep.advisory ? "warn" : "fail"} | ${seconds}s |`);
  }

  const report = [
    `# Weekly sweep — ${date}`,
    "",
    "Generated by `scripts/weekly.ts`. This is the replenishment point: every",
    "finding below becomes a dated ROADMAP/register action or an explicit",
    "record-and-close.",
    "",
    "| Step | Command | Result | Time |",
    "|---|---|---|---|",
    ...rows,
    "",
    failed === 0 ? "All required steps passed." : `${failed} required step(s) failed — fix before the next increment.`,
    "",
  ].join("\n");

  mkdirSync(join(ROOT, "spec", "audit"), { recursive: true });
  const path = join(ROOT, "spec", "audit", `weekly-${date}.md`);
  writeFileSync(path, report);
  console.log(`\nweekly: wrote ${path}`);
  process.exit(failed > 0 ? 1 : 0);
}

try {
  main();
} catch (error) {
  console.error(`weekly: fatal: ${(error as Error).message}`);
  process.exit(2);
}
